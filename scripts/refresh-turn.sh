#!/usr/bin/env bash
set -euo pipefail
umask 077
PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"

APP_DIR="/opt/apps/game-coop"
ENV_FILE="$APP_DIR/.env"
CONFIG_DIR="$APP_DIR/config"
CONFIG_FILE="$CONFIG_DIR/config.yml"
NO_RESTART=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --no-restart)
      NO_RESTART=1
      shift
      ;;
    *)
      echo "Usage: $0 [--no-restart]" >&2
      exit 1
      ;;
  esac
done

read_env_var() {
  local target_key="$1"
  local line="" val="" found_val=""
  if [[ ! -f "$ENV_FILE" ]]; then
    echo "Error: Missing $ENV_FILE" >&2
    return 1
  fi
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^[[:space:]]*(#|$) ]] && continue
    if [[ "$line" == "${target_key}="* ]]; then
      val="${line#*=}"
      if [[ ${#val} -ge 2 ]]; then
        if [[ "${val:0:1}" == '"' && "${val: -1}" == '"' ]]; then
          val="${val:1:${#val}-2}"
        elif [[ "${val:0:1}" == "'" && "${val: -1}" == "'" ]]; then
          val="${val:1:${#val}-2}"
        fi
      fi
      found_val="$val"
    fi
  done < "$ENV_FILE"
  printf '%s' "$found_val"
}

for cmd in curl jq; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: Required command '$cmd' not found" >&2
    exit 1
  fi
done

CF_TURN_KEY_ID="$(read_env_var CLOUDFLARE_TURN_KEY_ID)"
CF_TURN_API_TOKEN="$(read_env_var CLOUDFLARE_TURN_API_TOKEN)"

if [[ -z "$CF_TURN_KEY_ID" || "$CF_TURN_KEY_ID" == CHANGE_ME_* ]]; then
  echo "Error: CLOUDFLARE_TURN_KEY_ID is unset or still a placeholder in .env" >&2
  exit 1
fi

if [[ -z "$CF_TURN_API_TOKEN" || "$CF_TURN_API_TOKEN" == CHANGE_ME_* ]]; then
  echo "Error: CLOUDFLARE_TURN_API_TOKEN is unset or still a placeholder in .env" >&2
  exit 1
fi

mkdir -p "$CONFIG_DIR"
TMP_JSON="$(mktemp "$CONFIG_DIR/.tmp-turn-response.XXXXXX.json")"
TMP_YAML="$(mktemp "$CONFIG_DIR/.tmp-config.XXXXXX.yml")"
trap 'rm -f "${TMP_JSON:-}" "${TMP_YAML:-}"' EXIT

printf 'header = "Authorization: Bearer %s"\n' "$CF_TURN_API_TOKEN" | \
  curl -fsS --max-time 20 -X POST \
    -K - \
    -H "Content-Type: application/json" \
    --data '{"ttl": 172800}' \
    "https://rtc.live.cloudflare.com/v1/turn/keys/${CF_TURN_KEY_ID}/credentials/generate-ice-servers" \
    -o "$TMP_JSON"

if ! jq -e '
  (.iceServers | type == "array" and length > 0) and
  ([.iceServers[]
    | select(((.username // "") | length > 0) and ((.credential // "") | length > 0))
    | (.urls | if type == "array" then .[] else . end)
    | select(type == "string" and (startswith("turn:") or startswith("turns:")) and (test(":53($|\\?)") | not))
  ] | length > 0)
' "$TMP_JSON" >/dev/null; then
  echo "Error: Cloudflare TURN API response missing valid iceServers with TURN credentials" >&2
  exit 1
fi

{
  printf '# Auto-generated by scripts/refresh-turn.sh (Cloudflare Realtime TURN, TTL 48h).\n'
  printf '# Do not commit this file to Git.\n\n'
  printf 'emulatorjs:\n'
  printf '  netplay:\n'
  printf '    enabled: true\n'
  printf '    ice_servers:\n'
  jq -r '
    .iceServers[]
    | (.username // "") as $u
    | (.credential // "") as $c
    | (.urls | if type == "array" then .[] else . end)
    | select(type == "string" and length > 0 and (test(":53($|\\?)") | not))
    | if ($u != "" and $c != "") then
        "      - urls: \(. | @json)\n        username: \($u | @json)\n        credential: \($c | @json)"
      else
        "      - urls: \(. | @json)"
      end
  ' "$TMP_JSON"
} > "$TMP_YAML"

if [[ ! -s "$TMP_YAML" ]] || ! grep -Eq '^[[:space:]]*- urls: "turns?:' "$TMP_YAML"; then
  echo "Error: Generated TURN YAML config failed validation" >&2
  exit 1
fi

chmod 600 "$TMP_YAML"
mv -f "$TMP_YAML" "$CONFIG_FILE"

ENTRY_COUNT="$(grep -c '^[[:space:]]*- urls:' "$CONFIG_FILE" || true)"
RESTARTED="no (skipped via --no-restart)"

if [[ "$NO_RESTART" -eq 0 ]]; then
  if command -v docker >/dev/null 2>&1 && docker ps --filter "name=^/romm$" --filter "status=running" --format '{{.Names}}' | grep -qx romm; then
    docker compose -f "$APP_DIR/docker-compose.yml" restart romm >/dev/null
    RESTARTED="yes"
  else
    RESTARTED="no (romm container not running)"
  fi
fi

printf '[%s] Refreshed Cloudflare TURN config (%s ICE entries, TTL 172800s, romm restarted: %s)\n' \
  "$(date -Iseconds)" "$ENTRY_COUNT" "$RESTARTED"
